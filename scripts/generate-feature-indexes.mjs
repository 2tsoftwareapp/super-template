#!/usr/bin/env node
/** Check and generate feature package public barrels. */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const args = new Set(process.argv.slice(2));
const checkOnly = args.has("--check");
const dryRun = args.has("--dry-run");
const failures = [];

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, "utf8"));
}

function featurePackages() {
  const packagesRoot = path.join(root, "packages");
  return fs
    .readdirSync(packagesRoot, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name.startsWith("feature-"))
    .map((entry) => path.join(packagesRoot, entry.name))
    .filter((directory) => fs.existsSync(path.join(directory, "package.json")));
}

function exportName(file, pattern) {
  const source = fs.readFileSync(file, "utf8");
  return source.match(pattern)?.[1] ?? null;
}

function discoverFeature(directory) {
  const src = path.join(directory, "src");
  const featureFile = fs.readdirSync(src).find((file) => file.endsWith(".feature.ts"));
  const featureName = featureFile
    ? exportName(
        path.join(src, featureFile),
        /export\s+(?:const|function|class)\s+([A-Za-z_$][\w$]*Feature)\b/,
      )
    : null;
  return { featureFile, featureName };
}

function buildBarrel(directory, manifest) {
  const src = path.join(directory, "src");
  const files = fs.readdirSync(src);
  const { featureFile, featureName } = discoverFeature(directory);
  const moduleTarget = manifest.exports?.["./module"];
  const moduleFile =
    typeof moduleTarget === "string"
      ? path.basename(moduleTarget)
      : files.find((file) => file.endsWith(".module.ts"));
  const moduleName = moduleFile
    ? exportName(path.join(src, moduleFile), /export\s+class\s+([A-Za-z_$][\w$]*Module)\b/)
    : null;
  const lines = [
    "// Auto-generated by scripts/generate-feature-indexes.mjs.",
    "// Keep this barrel focused on the package public composition API.",
    "",
  ];
  if (featureFile && featureName) {
    lines.push(`export { ${featureName} } from "./${featureFile.replace(/\.ts$/, "")}";`);
  }
  if (moduleFile && moduleName) {
    lines.push(`export { ${moduleName} } from "./${moduleFile.replace(/\.ts$/, "")}";`);
  }
  if (fs.existsSync(path.join(src, "public/contracts.ts"))) {
    lines.push('export * from "./public/contracts";');
  }
  if (fs.existsSync(path.join(src, "testing/index.ts"))) {
    lines.push('export * from "./testing";');
  }
  return lines.length > 3 ? `${lines.join("\n")}\n` : null;
}

function validateManifestExports(directory, manifest) {
  const relativeDirectory = path.relative(root, directory);
  for (const [subpath, target] of Object.entries(manifest.exports ?? {})) {
    if (typeof target !== "string") continue;
    const targetPath = path.join(directory, target.replace(/^\.\//, ""));
    if (!fs.existsSync(targetPath)) {
      failures.push(`${relativeDirectory}: ${subpath} targets missing ${target}`);
    }
  }
}

const missing = [];
for (const directory of featurePackages()) {
  const manifest = readJson(path.join(directory, "package.json"));
  const index = path.join(directory, "src/index.ts");
  const relativeDirectory = path.relative(root, directory);
  validateManifestExports(directory, manifest);
  const { featureName } = discoverFeature(directory);
  if (!fs.existsSync(index)) {
    const content = buildBarrel(directory, manifest);
    if (content) missing.push({ index, content });
  } else if (featureName) {
    const source = fs.readFileSync(index, "utf8");
    const featurePattern = new RegExp(`\\b${featureName}\\b`);
    if (!featurePattern.test(source)) {
      failures.push(
        `${relativeDirectory}: src/index.ts does not export discovered manifest ${featureName}`,
      );
    }
  }
}

for (const { index, content } of missing) {
  const relative = path.relative(root, index);
  if (checkOnly || dryRun) {
    console.log(`${checkOnly ? "MISSING" : "WOULD CREATE"} ${relative}`);
    if (dryRun) console.log(content);
  } else {
    fs.writeFileSync(index, content, "utf8");
    console.log(`CREATED ${relative}`);
  }
}

if (failures.length > 0) {
  for (const failure of failures) console.error(`INVALID ${failure}`);
  process.exitCode = 1;
}
if (checkOnly && missing.length > 0) process.exitCode = 1;
if (!checkOnly && !dryRun && missing.length === 0) {
  console.log("No missing feature src/index.ts barrels found.");
}
if (dryRun) console.log(`Would create ${missing.length} file(s).`);
