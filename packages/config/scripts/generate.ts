/**
 * Serializes the TS source of truth (src/app-config.ts) into cross-runtime
 * artifacts:
 *   - generated/config.json           — canonical, consumable by any runtime
 *   - apps/mobile/lib/generated/config/shared_config.dart — for the Flutter app
 *
 * Run via `pnpm --filter @repo/config generate`. Committed like the OpenAPI
 * clients so the repo stays reproducible without a build step.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { appConfig } from "../src/app-config";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const packageDir = resolve(scriptDir, "..");
const repoRoot = resolve(packageDir, "..", "..");

const GENERATED_HEADER =
  "// GENERATED by @repo/config — do not edit by hand.\n" +
  "// Source of truth: packages/config/src/app-config.ts\n" +
  "// Regenerate with: pnpm --filter @repo/config generate\n";

type Json =
  | string
  | number
  | boolean
  | readonly Json[]
  | { readonly [key: string]: Json };

function writeJson(): void {
  const outDir = resolve(packageDir, "generated");
  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    resolve(outDir, "config.json"),
    `${JSON.stringify(appConfig, null, 2)}\n`,
    "utf8",
  );
}

// --- Dart emitter -----------------------------------------------------------

function toPascalCase(key: string): string {
  return key.charAt(0).toUpperCase() + key.slice(1);
}

function dartScalar(value: string | number | boolean): {
  type: string;
  literal: string;
} {
  if (typeof value === "boolean") {
    return { type: "bool", literal: String(value) };
  }
  if (typeof value === "number") {
    return Number.isInteger(value)
      ? { type: "int", literal: String(value) }
      : { type: "double", literal: String(value) };
  }
  return { type: "String", literal: JSON.stringify(value) };
}

function dartField(key: string, value: Json): string {
  if (Array.isArray(value)) {
    if (value.length === 0) {
      return `  static const List<Object> ${key} = [];`;
    }
    const elemType = dartScalar(value[0] as string | number | boolean).type;
    const literals = value
      .map((item) => dartScalar(item as string | number | boolean).literal)
      .join(", ");
    return `  static const List<${elemType}> ${key} = [${literals}];`;
  }
  const { type, literal } = dartScalar(value as string | number | boolean);
  return `  static const ${type} ${key} = ${literal};`;
}

function writeDart(): void {
  const classes: string[] = [];

  for (const [section, values] of Object.entries(appConfig)) {
    const className = `Shared${toPascalCase(section)}Config`;
    const fields = Object.entries(values as Record<string, Json>)
      .map(([key, value]) => dartField(key, value))
      .join("\n");
    classes.push(`class ${className} {\n  const ${className}._();\n\n${fields}\n}`);
  }

  const body = `${GENERATED_HEADER}\n${classes.join("\n\n")}\n`;
  const outPath = resolve(
    repoRoot,
    "apps/mobile/lib/generated/config/shared_config.dart",
  );
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, body, "utf8");
}

writeJson();
writeDart();

console.log("@repo/config: generated config.json + shared_config.dart");
